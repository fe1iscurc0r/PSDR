#!/usr/bin/env python3
"""Rebuild the 2.6.1 reference board end to end and hash the deliverables.

One command regenerates the KiCad board, its DRC report, the Gerber/drill
package under ``dist/kicad/fab``, optionally re-runs the reconciliation against
the upstream 2.6.1 CAM package, and writes ``dist/kicad/SHA256SUMS``.

The board is byte-identical between runs (UUIDs are uuid5 over the emission
order).  KiCad stamps its Gerber and drill files with a creation date, so those
are hashed with the timestamp metadata stripped; the DRC report is not hashed
because KiCad lists DRC items in a run-dependent order even when the counts are
identical.

``--check`` regenerates into a temporary directory and compares against the
manifest without touching the working copies.
"""
import argparse
import hashlib
import os
import re
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BOARD_NAME = "PSDR_2.6.1_pcb_spike_full"
DIST = os.path.join(ROOT, "dist", "kicad")
BOARD = os.path.join(DIST, BOARD_NAME + ".kicad_pcb")
DRC = os.path.join(DIST, "drc_" + BOARD_NAME + ".txt")
FAB = os.path.join(DIST, "fab")
MANIFEST = os.path.join(DIST, "SHA256SUMS")
LAYERS = "F.Cu,In1.Cu,In2.Cu,B.Cu,F.Silkscreen,B.Silkscreen,F.Mask,B.Mask"
KICAD_DEFAULT = r"C:/Users/ASUS/AppData/Local/Programs/KiCad/10.0/bin/kicad-cli.exe"
STAMP = re.compile(
    r"^(%TF\.CreationDate|%TF\.ProjectId|G04 Created by KiCad|"
    r"; DRILL file KiCad|; #@! TF\.CreationDate)")


def find_kicad(explicit):
    for cand in (explicit, os.environ.get("KICAD_CLI"), shutil.which("kicad-cli"),
                 KICAD_DEFAULT):
        if cand and os.path.isfile(cand):
            return cand
    raise SystemExit("kicad-cli not found; pass --kicad-cli or set KICAD_CLI")


def run(cmd, **kw):
    print("$ " + " ".join(cmd))
    subprocess.run(cmd, check=True, **kw)


def generate_board(out_board):
    run([sys.executable, os.path.join(ROOT, "tools", "pads_asc_pcb.py"),
         os.path.join(ROOT, "Hardware", "PSDR.asc"), "--all", "-o", out_board])


def export_fab(kicad, board, out_dir):
    if os.path.isdir(out_dir):
        shutil.rmtree(out_dir)  # generated output; stale layers must not linger
    os.makedirs(out_dir, exist_ok=True)
    run([kicad, "pcb", "export", "gerbers", "-o", out_dir, "--no-protel-ext",
         "--precision", "6", "--check-zones", "-l", LAYERS, board])
    run([kicad, "pcb", "export", "drill", "-o", out_dir, "--format", "excellon",
         "--excellon-units", "mm", "--excellon-zeros-format", "decimal",
         "--drill-origin", "absolute", board])
    # The converter writes a per-board project-local settings file next to the
    # board; it is not a deliverable.
    prl = os.path.splitext(board)[0] + ".kicad_prl"
    if os.path.isfile(prl):
        os.remove(prl)


def normalized_sha256(path):
    lines = open(path, encoding="latin-1").read().splitlines()
    keep = [l for l in lines if not STAMP.match(l)]
    return hashlib.sha256(("\n".join(keep) + "\n").encode("latin-1")).hexdigest()


def exact_sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def collect(board, fab_dir):
    """Return [(relpath, kind, sha256)]; kind is 'exact' or 'normalized'."""
    rows = [(BOARD_NAME + ".kicad_pcb", "exact", exact_sha256(board))]
    for name in sorted(os.listdir(fab_dir)):
        if name.endswith(".gbrjob"):
            continue  # carries its own creation date and no fab content
        path = os.path.join(fab_dir, name)
        rows.append(("fab/" + name, "normalized", normalized_sha256(path)))
    return rows


def write_manifest(rows, pads_label):
    lines = [
        "# SHA256 manifest for the 2.6.1 KiCad reference board.",
        "# Generated by tools/reproduce_kicad.py.",
        "#",
        "# 'exact' rows hash the file as committed.  The board is deterministic.",
        "# 'normalized' rows hash the KiCad Gerber/drill files with their",
        "# creation-date metadata removed (%TF.CreationDate, the G04 date line,",
        "# the drill date header, and %TF.ProjectId); the raw files differ on",
        "# every run only in those lines.",
        "# The DRC report is not listed: KiCad emits the same violation counts",
        "# but reports the items in a run-dependent order.",
    ]
    if pads_label:
        lines.append("# Reconciled against the upstream 2.6.1 CAM package:")
        lines.append("#   " + pads_label)
    for rel, kind, digest in rows:
        lines.append(f"{digest}  {rel}  [{kind}]")
    open(MANIFEST, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    print("wrote", MANIFEST)


def parse_manifest():
    rows = []
    for line in open(MANIFEST, encoding="utf-8"):
        if line.startswith("#") or not line.strip():
            continue
        m = re.match(r"^([0-9a-f]{64})  (\S+)  \[(exact|normalized)\]$", line.rstrip())
        if not m:
            raise SystemExit(f"bad manifest line: {line!r}")
        rows.append((m.group(2), m.group(3), m.group(1)))
    return rows


def verify(kicad, pads_gerbers):
    rows = parse_manifest()
    tmp = tempfile.mkdtemp(prefix="psdr-repro-")
    try:
        board = os.path.join(tmp, BOARD_NAME + ".kicad_pcb")
        generate_board(board)
        fab = os.path.join(tmp, "fab")
        export_fab(kicad, board, fab)
        fresh = {rel: (kind, digest) for rel, kind, digest in collect(board, fab)}
        failed = 0
        for rel, kind, digest in rows:
            got = fresh.get(rel)
            status = "OK" if got and got[1] == digest else "DIFF"
            if status == "DIFF":
                failed += 1
            print(f"{status:4s} {rel}")
        extra = sorted(set(fresh) - {rel for rel, _, _ in rows})
        for rel in extra:
            print(f"EXTRA {rel}")
        if failed:
            raise SystemExit(f"{failed} file(s) differ from the manifest")
        print("all files match the manifest")
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--kicad-cli", help="path to kicad-cli")
    ap.add_argument("--pads-gerbers",
                    help="upstream 'PSDR261 Main Board' Gerber directory (from 468dc41)")
    ap.add_argument("--pads-label", default="upstream 468dc41, "
                    "Hardware/Gerbers/PSDR261 Main Board",
                    help="manifest label for the CAM package used above")
    ap.add_argument("--no-compare", action="store_true",
                    help="skip the pad/drill reconciliation")
    ap.add_argument("--check", action="store_true",
                    help="regenerate into a temp dir and verify the manifest")
    args = ap.parse_args()
    kicad = find_kicad(args.kicad_cli)
    if args.check:
        verify(kicad, args.pads_gerbers)
        return
    os.makedirs(DIST, exist_ok=True)
    generate_board(BOARD)
    run([kicad, "pcb", "drc", "--severity-all", "--refill-zones",
         "-o", DRC, BOARD])
    export_fab(kicad, BOARD, FAB)
    if args.pads_gerbers and not args.no_compare:
        out = os.path.join(DIST, "gerber_compare.txt")
        with open(out, "w", encoding="utf-8", newline="\n") as fh:
            subprocess.run([sys.executable,
                            os.path.join(ROOT, "tools", "kicad_gerber_compare.py"),
                            "--pads", args.pads_gerbers, "--fab", FAB,
                            "--board", BOARD_NAME],
                           check=True, stdout=fh, stderr=subprocess.STDOUT)
        print("wrote", out)
    label = args.pads_label if (args.pads_gerbers and not args.no_compare) else ""
    write_manifest(collect(BOARD, FAB), label)


if __name__ == "__main__":
    main()
